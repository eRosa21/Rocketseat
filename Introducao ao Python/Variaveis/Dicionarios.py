## coleção não ordenada

pessoa = {"nome":"Roger","idade":30,"genero":"masculino"}
print(pessoa)


##Acessar valores separados
print("Nome:", pessoa["nome"])
print("Idade:",pessoa["idade"])

## adicionando uma chave após a criação do dicionario

pessoa["sobrenome"] = "Rogério"
print(pessoa)

## alterando umma chave existente

pessoa["idade"] = 31
print(pessoa)

